-- ============================================================
-- 浩海 study · P0 升级脚本 v4（身份层 + 课程中心 + 组队广场）
-- 用法：Supabase → SQL Editor → New query → 全选粘贴 → Run
-- 说明：本脚本可重复执行，不会删数据；请先执行过 v3（supabase-setup.sql）
--
-- 这次新增：
--   1) profiles        用户资料（昵称/学院/专业/年级/认证状态）
--   2) courses         课程（课程中心的主表）
--   3) course_reviews  课程攻略/评价（一人一课一条）
--   4) teams           组队（竞赛/课程大作业/学习搭子）
--   5) team_applications 入队申请
--   6) site_items.course_id  让现有资料挂到课程上
--
-- 权限设计：
--   · 所有人可读课程/组队/课程评价；游客不能写
--   · 只有「已认证」用户能建课程、发组队、写评价（认证在服务端校验）
--   · 只能改/删自己发布的内容；管理员走 service_role 绕过 RLS
--   · profiles 的 verified 字段普通用户无权修改（列级授权）
-- ============================================================

-- ------------------------------------------------------------
-- 1. 用户资料
-- ------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nickname text,
  college text,            -- 学院
  major text,              -- 专业
  grade text,              -- 年级/入学年份，如 2024
  bio text,                -- 一句话自我介绍
  verified boolean not null default false,   -- 是否已校园认证
  verify_method text,      -- email / invite / admin
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "profiles_read" on public.profiles;
create policy "profiles_read" on public.profiles
  for select to anon, authenticated using (true);

drop policy if exists "profiles_insert_self" on public.profiles;
create policy "profiles_insert_self" on public.profiles
  for insert to authenticated with check (id = auth.uid());

drop policy if exists "profiles_update_self" on public.profiles;
create policy "profiles_update_self" on public.profiles
  for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());

-- 列级授权：普通用户只能改资料字段，不能自己把 verified 改成 true
-- （insert 也只放开资料字段，防止有人绕过触发器直接插入 verified=true 的行）
revoke update on public.profiles from authenticated;
revoke insert on public.profiles from authenticated;
grant update (nickname, college, major, grade, bio) on public.profiles to authenticated;
grant insert (id, nickname, college, major, grade, bio) on public.profiles to authenticated;
grant select on public.profiles to anon, authenticated;

-- 注册后自动建一条 profiles（触发器失败也不阻塞注册：on conflict do nothing）
-- 用 DO 块包起来：万一当前数据库角色没有 auth.users 的 TRIGGER 权限，
-- 只跳过触发器并给出提示，不会让后面的建表语句中断。
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, nickname)
  values (new.id, split_part(coalesce(new.email, '同学'), '@', 1))
  on conflict (id) do nothing;
  return new;
end;
$$;

do $$
begin
  execute 'drop trigger if exists on_auth_user_created on auth.users';
  execute 'create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user()';
exception
  when insufficient_privilege then
    raise notice '跳过 auth.users 触发器（无权限）。注册后第一次保存资料会自动创建 profiles 行。';
end $$;

-- 给已经注册过的用户补一条资料（无权限时跳过，不影响后续建表）
do $$
begin
  insert into public.profiles (id, nickname)
  select u.id, split_part(coalesce(u.email, '同学'), '@', 1)
  from auth.users u
  on conflict (id) do nothing;
exception
  when insufficient_privilege then
    raise notice '跳过历史用户 profiles 回填（无 auth.users 读取权限）。';
end $$;

-- updated_at 自动刷新
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_touch on public.profiles;
create trigger profiles_touch
  before update on public.profiles
  for each row execute function public.touch_updated_at();

-- ------------------------------------------------------------
-- 2. 课程
-- ------------------------------------------------------------
create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  name text not null,
  code text,               -- 课程代码（可空）
  teacher text,
  college text,
  credit numeric(3,1),
  term text,               -- 如 2025-2026-1
  exam_type text,          -- 考试 / 论文 / 大作业 / 考查
  intro text,
  created_by uuid references auth.users(id) on delete set null,
  status text not null default 'approved' check (status in ('approved', 'hidden')),
  created_at timestamptz not null default now()
);

create index if not exists courses_name_idx on public.courses (lower(name));
create unique index if not exists courses_name_teacher_uidx
  on public.courses (lower(name), coalesce(lower(teacher), ''));

alter table public.courses enable row level security;

drop policy if exists "courses_read" on public.courses;
create policy "courses_read" on public.courses
  for select to anon, authenticated using (status = 'approved' or created_by = auth.uid());

drop policy if exists "courses_insert_verified" on public.courses;
create policy "courses_insert_verified" on public.courses
  for insert to authenticated
  with check (
    created_by = auth.uid()
    and exists (select 1 from public.profiles p where p.id = auth.uid() and p.verified)
  );

drop policy if exists "courses_update_own" on public.courses;
create policy "courses_update_own" on public.courses
  for update to authenticated
  using (created_by = auth.uid()) with check (created_by = auth.uid());

drop policy if exists "courses_delete_own" on public.courses;
create policy "courses_delete_own" on public.courses
  for delete to authenticated using (created_by = auth.uid());

grant select on public.courses to anon, authenticated;
grant insert, update, delete on public.courses to authenticated;

-- ------------------------------------------------------------
-- 3. 课程攻略 / 评价（一人一课一条，可修改）
-- ------------------------------------------------------------
create table if not exists public.course_reviews (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating int not null default 5 check (rating between 1 and 5),
  content text not null,
  term text,
  status text not null default 'approved' check (status in ('approved', 'hidden')),
  created_at timestamptz not null default now(),
  unique (course_id, user_id)
);

create index if not exists course_reviews_course_idx on public.course_reviews (course_id);

alter table public.course_reviews enable row level security;

drop policy if exists "reviews_read" on public.course_reviews;
create policy "reviews_read" on public.course_reviews
  for select to anon, authenticated using (status = 'approved' or user_id = auth.uid());

drop policy if exists "reviews_insert_verified" on public.course_reviews;
create policy "reviews_insert_verified" on public.course_reviews
  for insert to authenticated
  with check (
    user_id = auth.uid()
    and length(content) between 1 and 800
    and exists (select 1 from public.profiles p where p.id = auth.uid() and p.verified)
  );

drop policy if exists "reviews_update_own" on public.course_reviews;
create policy "reviews_update_own" on public.course_reviews
  for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "reviews_delete_own" on public.course_reviews;
create policy "reviews_delete_own" on public.course_reviews
  for delete to authenticated using (user_id = auth.uid());

grant select on public.course_reviews to anon, authenticated;
grant insert, update, delete on public.course_reviews to authenticated;

-- ------------------------------------------------------------
-- 4. 组队
-- ------------------------------------------------------------
create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  title text not null,
  kind text not null default 'competition' check (kind in ('competition', 'course', 'study')),
  competition text,        -- 比赛名称（kind=competition 时）
  course_id bigint references public.courses(id) on delete set null,
  skills text,             -- 需要的技能，英文逗号分隔，如 前端,UI,答辩
  need_count int not null default 3 check (need_count between 2 and 20),
  joined_count int not null default 1,   -- 已确认队员数（含队长）
  desc_text text,
  deadline date,
  owner_id uuid not null references auth.users(id) on delete cascade,
  owner_nickname text,     -- 冗余存一份，列表页不用联表
  owner_college text,
  status text not null default 'open' check (status in ('open', 'closed')),
  created_at timestamptz not null default now()
);

create index if not exists teams_status_idx on public.teams (status, created_at desc);
create index if not exists teams_course_idx on public.teams (course_id);

alter table public.teams enable row level security;

drop policy if exists "teams_read" on public.teams;
create policy "teams_read" on public.teams
  for select to anon, authenticated using (true);

drop policy if exists "teams_insert_verified" on public.teams;
create policy "teams_insert_verified" on public.teams
  for insert to authenticated
  with check (
    owner_id = auth.uid()
    and exists (select 1 from public.profiles p where p.id = auth.uid() and p.verified)
  );

drop policy if exists "teams_update_own" on public.teams;
create policy "teams_update_own" on public.teams
  for update to authenticated
  using (owner_id = auth.uid()) with check (owner_id = auth.uid());

drop policy if exists "teams_delete_own" on public.teams;
create policy "teams_delete_own" on public.teams
  for delete to authenticated using (owner_id = auth.uid());

grant select on public.teams to anon, authenticated;
grant insert, update, delete on public.teams to authenticated;

-- ------------------------------------------------------------
-- 5. 入队申请
-- ------------------------------------------------------------
create table if not exists public.team_applications (
  id bigint generated by default as identity primary key,
  team_id bigint not null references public.teams(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  message text,
  status text not null default 'pending' check (status in ('pending', 'accepted', 'rejected')),
  created_at timestamptz not null default now(),
  unique (team_id, user_id)
);

create index if not exists team_apps_team_idx on public.team_applications (team_id, status);
create index if not exists team_apps_user_idx on public.team_applications (user_id);

alter table public.team_applications enable row level security;

-- 申请人看自己的；队长看自己队的
drop policy if exists "team_apps_read" on public.team_applications;
create policy "team_apps_read" on public.team_applications
  for select to authenticated
  using (
    user_id = auth.uid()
    or exists (select 1 from public.teams t where t.id = team_id and t.owner_id = auth.uid())
  );

drop policy if exists "team_apps_insert" on public.team_applications;
create policy "team_apps_insert" on public.team_applications
  for insert to authenticated
  with check (
    user_id = auth.uid()
    and length(coalesce(message, '')) <= 500
    and exists (select 1 from public.profiles p where p.id = auth.uid() and p.verified)
    and exists (
      select 1 from public.teams t
      where t.id = team_id and t.status = 'open' and t.owner_id <> auth.uid()
    )
  );

-- 只有队长能改申请状态（通过/拒绝）
drop policy if exists "team_apps_update_owner" on public.team_applications;
create policy "team_apps_update_owner" on public.team_applications
  for update to authenticated
  using (exists (select 1 from public.teams t where t.id = team_id and t.owner_id = auth.uid()))
  with check (exists (select 1 from public.teams t where t.id = team_id and t.owner_id = auth.uid()));

-- 申请人可以撤回自己还在 pending 的申请
drop policy if exists "team_apps_delete_own" on public.team_applications;
create policy "team_apps_delete_own" on public.team_applications
  for delete to authenticated using (user_id = auth.uid() and status = 'pending');

grant select, insert, update, delete on public.team_applications to authenticated;

-- ------------------------------------------------------------
-- 6. 现有资料挂到课程上
-- ------------------------------------------------------------
alter table public.site_items add column if not exists course_id bigint;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'site_items_course_fk') then
    alter table public.site_items
      add constraint site_items_course_fk
      foreign key (course_id) references public.courses(id) on delete set null;
  end if;
end $$;

create index if not exists site_items_course_idx on public.site_items (course_id);

-- ------------------------------------------------------------
-- 7. 自增主键的序列授权（否则登录用户 insert 会报 permission denied for sequence）
-- ------------------------------------------------------------
grant usage, select on all sequences in schema public to authenticated;

